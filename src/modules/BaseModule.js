/**
 * Базовый класс для всех модулей просмотрщика
 * Определяет интерфейс и общие методы для модулей
 */
export class BaseModule {
  /**
   * Создает экземпляр модуля
   * @param {Viewer} viewer - экземпляр просмотрщика
   */
  constructor(viewer) {
    this.viewer = viewer;
    this.isActive = false;
  }

  /**
   * Активирует модуль
   */
  activate() {
    this.isActive = true;
  }

  /**
   * Деактивирует модуль и сбрасывает его состояние
   */
  deactivate() {
    this.isActive = false;
    this.reset();
  }

  /**
   * Сбрасывает состояние модуля к начальному
   * Переопределяется в дочерних классах
   */
  reset() {
    // Переопределяется в дочерних классах
  }

  /**
   * Возвращает статус активности модуля
   * @returns {boolean} true если модуль активен
   */
  getIsActive() {
    return this.isActive;
  }

  /**
   * Вызывается на каждом кадре анимации
   * Переопределяется в дочерних классах для обновления состояния
   */
  update() {
    // Переопределяется в дочерних классах
  }
}
